#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.11"
# dependencies = ["pydantic>=2", "pyyaml"]
# ///
"""Regenerate papers/index.md from the frontmatter of every paper note.

Also enforces the store's rule 1: a note may not leave `queued` with an empty
`## Claim`. Violations are listed in the index and printed to stderr.

Usage:  python3 papers/bin/reindex.py   (or ./reindex.py — uv resolves deps)
"""

from __future__ import annotations

import re
import sys
from datetime import date
from enum import StrEnum
from pathlib import Path

import yaml
from pydantic import BaseModel, Field, ValidationError

PAPERS = Path(__file__).resolve().parent.parent
SKIP = {"index.md", "_template.md", "README.md"}
FRONTMATTER = re.compile(r"\A---\n(.*?)\n---\n(.*)\Z", re.DOTALL)
# A section body counts as empty if it is only whitespace, HTML comments,
# and bare "-" placeholder bullets.
PLACEHOLDER = re.compile(r"(<!--.*?-->|^\s*-\s*$|\s)", re.DOTALL | re.MULTILINE)


class Status(StrEnum):
    queued = "queued"
    skimmed = "skimmed"
    read = "read"
    reimplemented = "reimplemented"
    dropped = "dropped"


ORDER = [Status.read, Status.reimplemented, Status.skimmed, Status.queued, Status.dropped]


class PaperMeta(BaseModel):
    citekey: str
    title: str
    authors: list[str] = []
    year: int | None = None
    venue: str | None = None
    url: str | None = None
    added: date | None = None
    status: Status = Status.queued
    rating: int | None = Field(default=None, ge=1, le=5)
    tags: list[str] = []
    related: list[str] = []


class Note(BaseModel):
    path: Path
    meta: PaperMeta
    has_claim: bool

    @property
    def problem(self) -> str | None:
        if self.meta.status is not Status.queued and not self.has_claim:
            return f"status `{self.meta.status}` but `## Claim` is empty"
        if self.meta.citekey != self.path.stem:
            return f"citekey `{self.meta.citekey}` does not match filename"
        return None


def section(body: str, heading: str) -> str:
    """Return the text under '## <heading>' up to the next '## ' heading."""
    match = re.search(rf"^## {re.escape(heading)}\s*$(.*?)(?=^## |\Z)", body, re.DOTALL | re.MULTILINE)
    return match.group(1) if match else ""


def load(path: Path) -> Note | None:
    match = FRONTMATTER.match(path.read_text())
    if not match:
        print(f"skip (no frontmatter): {path.name}", file=sys.stderr)
        return None
    try:
        meta = PaperMeta.model_validate(yaml.safe_load(match.group(1)) or {})
    except ValidationError as exc:
        print(f"skip (bad frontmatter): {path.name}\n{exc}", file=sys.stderr)
        return None
    claim = PLACEHOLDER.sub("", section(match.group(2), "Claim"))
    return Note(path=path, meta=meta, has_claim=bool(claim.strip()))


def row(note: Note) -> str:
    m = note.meta
    stars = "★" * m.rating if m.rating else ""
    tags = " ".join(f"`{t}`" for t in m.tags)
    return f"| [{m.citekey}]({note.path.name}) | {m.title} | {m.year or ''} | {tags} | {stars} |"


def main() -> int:
    notes = [n for n in (load(p) for p in sorted(PAPERS.glob("*.md")) if p.name not in SKIP) if n]

    lines = [
        "# Paper index",
        "",
        "<!-- GENERATED by bin/reindex.py — do not hand-edit. -->",
        "",
        f"{len(notes)} papers.",
        "",
    ]
    for status in ORDER:
        group = [n for n in notes if n.meta.status is status]
        if not group:
            continue
        group.sort(key=lambda n: (-(n.meta.year or 0), n.meta.citekey))
        lines += [
            f"## {status} ({len(group)})",
            "",
            "| key | title | year | tags | rating |",
            "| --- | --- | --- | --- | --- |",
            *(row(n) for n in group),
            "",
        ]

    problems = [(n, p) for n in notes if (p := n.problem)]
    if problems:
        lines += ["## Problems", ""]
        lines += [f"- `{n.meta.citekey}` — {p}" for n, p in problems]
        lines += [""]
        for note, problem in problems:
            print(f"PROBLEM {note.meta.citekey}: {problem}", file=sys.stderr)

    (PAPERS / "index.md").write_text("\n".join(lines))
    print(f"indexed {len(notes)} papers, {len(problems)} problems -> {PAPERS / 'index.md'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
